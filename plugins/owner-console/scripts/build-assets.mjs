import { readFile, writeFile } from 'node:fs/promises'
import { extname } from 'node:path'

/**
 * Inlines the committed, pre-compressed artwork under `assets/` as data URIs in
 * `src/artwork.ts`. The Web client bundle must stay self-contained: no network fetch, no
 * bundler asset loading, so every image ships inside `lib/client.js`.
 *
 * Pipeline (see README "界面布局"):
 *   python3 scripts/prepare-assets.py   # only when the 11 深海觉醒 source artwork changes
 *   node scripts/build-assets.mjs       # every build; deterministic from assets/
 */

const directory = new URL('../assets/', import.meta.url)
const mime = new Map([['.webp', 'image/webp'], ['.png', 'image/png'], ['.jpg', 'image/jpeg']])

async function dataUri(name) {
  const bytes = await readFile(new URL(name, directory))
  const type = mime.get(extname(name))
  if (type === undefined) throw new Error(`build-assets: unsupported asset type ${name}`)
  return `data:${type};base64,${bytes.toString('base64')}`
}

const [hero, backdrop, icon, seal] = await Promise.all([
  dataUri('hero.webp'), dataUri('backdrop.webp'), dataUri('icon-128.webp'), dataUri('icon-256.webp'),
])

const source = `/**
 * Generated by \`node scripts/build-assets.mjs\` from the committed files under \`assets/\`.
 * Do not edit by hand; do not commit the multi-MB 11 深海觉醒 originals. The images are
 * inlined so the emitted Web client bundle needs no network or bundler asset loading.
 * Decorative only: every consumer renders them with \`alt=""\` + \`aria-hidden\`.
 */
export const WENYAO_HERO_WIDTH: number = 1254
export const WENYAO_HERO_HEIGHT: number = 418
export const WENYAO_HERO_DATA_URI: string =
  '${hero}'
export const WENYAO_BACKDROP_DATA_URI: string =
  '${backdrop}'
export const WENYAO_ICON_DATA_URI: string =
  '${icon}'
export const WENYAO_SEAL_DATA_URI: string =
  '${seal}'
`

const target = new URL('../src/artwork.ts', import.meta.url)
await writeFile(target, source, 'utf8')
console.log(`owner-console artwork: ${source.length} chars of inlined data URIs`)
